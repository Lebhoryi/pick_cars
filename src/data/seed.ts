type SpecPartial = { [K in keyof VehicleSpecs]?: Partial<VehicleSpecs[K]> }

function specs(partial: SpecPartial): VehicleSpecs {
  return {
    basic: { ...blankBasic(), ...partial.basic },
    powertrain: { ...blankPowertrain(), ...partial.powertrain },
    body: { ...blankBody(), ...partial.body },
    chassis: { ...blankChassis(), ...partial.chassis },
    comfort: { ...blankComfort(), ...partial.comfort },
    adas: { ...blankAdas(), ...partial.adas },
    safety: { ...blankSafety(), ...partial.safety },
  }
}

function p(status: Provenance['status'], sourceId: string, extra: Partial<Provenance> = {}): Provenance {
  return { status, sourceId, checkedAt: CHECK_DATE, ...extra }
}

function manual(scores: Partial<Record<ScoreDimId, number>>): Record<ScoreDimId, number | null> {
  const out = blankManualScores()
  for (const id of SCORE_DIM_IDS) out[id] = scores[id] ?? null
  return out
}

